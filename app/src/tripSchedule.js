export function getTripStatus(customDate = null) {
  const now = customDate || new Date()

  // Format Iceland (GMT) and Poland (CEST = GMT+2)
  const gmtHours = now.getUTCHours().toString().padStart(2, '0')
  const gmtMinutes = now.getUTCMinutes().toString().padStart(2, '0')
  const cestHours = ((now.getUTCHours() + 2) % 24).toString().padStart(2, '0')

  const timeStrIceland = `${gmtHours}:${gmtMinutes} GMT`
  const timeStrPoland = `${cestHours}:${gmtMinutes} CEST`

  if (now < TRIP_START_DATE) {
    const diffMs = TRIP_START_DATE - now
    const days = Math.floor(diffMs / (1000 * 60 * 60 * 24))
    const hours = Math.floor((diffMs / (1000 * 60 * 60)) % 24)
    const minutes = Math.floor((diffMs / (1000 * 60)) % 60)
    const seconds = Math.floor((diffMs / 1000) % 60)

    return {
      phase: 'before',
      phaseLabel: '⏳ ODLICZANIE DO STARTU',
      countdown: { days, hours, minutes, seconds },
      timeStrIceland,
      timeStrPoland,
      currentEvent: null,
      nextEvent: TRIP_EVENTS[0],
      tripProgress: 0,
    }
  }

  if (now > TRIP_END_DATE) {
    return {
      phase: 'after',
      phaseLabel: '🏁 WYPRAWA ZAKOŃCZONA',
      timeStrIceland,
      timeStrPoland,
      currentEvent: null,
      nextEvent: null,
      tripProgress: 100,
    }
  }

  // During trip
  let currentEvent = null
  let nextEvent = null

  for (let i = 0; i < TRIP_EVENTS.length; i++) {
    const ev = TRIP_EVENTS[i]
    if (now >= ev.start && now <= ev.end) {
      currentEvent = ev
      nextEvent = TRIP_EVENTS[i + 1] || null
      break
    }
    if (now < ev.start) {
      nextEvent = ev
      currentEvent = TRIP_EVENTS[i - 1] || null
      break
    }
  }

  const totalTripMs = TRIP_END_DATE - TRIP_START_DATE
  const elapsedMs = now - TRIP_START_DATE
  const tripProgress = Math.min(100, Math.max(0, Math.round((elapsedMs / totalTripMs) * 100)))

  return {
    phase: 'during',
    phaseLabel: currentEvent ? `🟢 TRWA: ${currentEvent.title}` : '🟢 W TRASIE',
    timeStrIceland,
    timeStrPoland,
    currentEvent,
    nextEvent,
    tripProgress,
  }
}
